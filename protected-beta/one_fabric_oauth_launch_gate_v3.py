"""8x8 native account-link launch preflight: signed-in tenant + provider OAuth registration.

Additive to existing one_fabric_native_provider_readiness_v2. This module cannot
start OAuth itself, handle callbacks, receive tokens, or authorize trading/posting.
The actual provider redirect and random one-use state must be generated by the
backend only after trusted callback allowlisting and atomic state persistence.
All LaunchPrerequisites flags must come from server-validated identity, backend
provider registration and protected persistence; never from user/MCP arguments.
"""
from __future__ import annotations
from dataclasses import dataclass
from typing import Optional

from one_fabric_native_provider_readiness_v2 import Admission, evaluate

FABRIC_ROOT = "fabric://8x8/core"
PROVIDER_ALPACA = "alpaca"
AUTH_MODE_ALPACA = "OAUTH2_PROVIDER_CONSENT"
PROVIDER_GUIDE = "https://docs.alpaca.markets/us/docs/using-oauth2-and-trading-api"
PROVIDER_REGISTER = "https://docs.alpaca.markets/us/docs/registering-your-app"

@dataclass(frozen=True)
class LaunchPrerequisites:
    admission: Admission
    verified_8x8_tenant_binding: bool
    oauth_app_registered: bool
    oauth_app_approved_for_use: bool
    client_id_server_configured: bool
    exact_redirect_registered: bool
    oauth_callback_server_ready: bool
    one_time_state_server_persistent: bool
    encrypted_token_storage_ready: bool
    paper_environment_only: bool

@dataclass(frozen=True)
class LaunchDecision:
    verdict: str
    reason: str
    provider: str = PROVIDER_ALPACA
    environment: str = "paper"
    read_only: bool = True
    user_authorization_url: Optional[str] = None
    connected: bool = False
    live_order_authorized: bool = False
    public_post_authorized: bool = False

def assess_alpaca_launch(p: LaunchPrerequisites) -> LaunchDecision:
    """ONLY readiness: never make up client IDs, callback URLs or authorization links."""
    def block(reason: str) -> LaunchDecision:
        return LaunchDecision("BLOCKED", reason)
    if not isinstance(p, LaunchPrerequisites) or not isinstance(p.admission, Admission):
        return block("INVALID_INPUT")
    a = p.admission
    if a.provider != PROVIDER_ALPACA or a.domain != "trading":
        return block("WRONG_PROVIDER_OR_DOMAIN")
    if p.paper_environment_only is not True:
        return block("PAPER_ONLY_FOR_FIRST_CONNECTION")
    # Reject credentials even if supplied through an otherwise complete admission.
    if a.raw_credential_submitted:
        return block("CREDENTIALS_MUST_NOT_ENTER_MCP_OR_CHAT")
    # Existing readiness checks cover jurisdiction, tenant, consent, scope and STOP.
    # The one deliberate exclusion is that no Vault handle exists yet at launch.
    if a.vault_handle_present is True or a.provider_canary_verified is True:
        return block("USE_EXISTING_CONNECTION_RECONCILIATION")
    base = evaluate(a)
    if base.verdict != "READY_FOR_PROTECTED_ENROLLMENT":
        return block("ADMISSION_" + base.reason)
    for name, reason in (
        ("verified_8x8_tenant_binding", "VERIFIED_8X8_ID_BINDING_REQUIRED"),
        ("oauth_app_registered", "REGISTER_ALPACA_CONNECT_APP"),
        ("oauth_app_approved_for_use", "ALPACA_APP_APPROVAL_REQUIRED"),
        ("client_id_server_configured", "SERVER_SIDE_OAUTH_CLIENT_REGISTRATION_REQUIRED"),
        ("exact_redirect_registered", "EXACT_OAUTH_REDIRECT_ALLOWLIST_REQUIRED"),
        ("oauth_callback_server_ready", "VERIFIED_CALLBACK_REQUIRED"),
        ("one_time_state_server_persistent", "PERSIST_ONE_USE_OAUTH_STATE"),
        ("encrypted_token_storage_ready", "TOKEN_VAULT_NOT_READY"),
    ):
        if getattr(p,name) is not True:
            return block(reason)
    # The actual redirect is created by an authenticated backend at request time,
    # never from a static or user-controlled client_id/redirect/state field.
    return LaunchDecision("READY_FOR_BACKEND_OAUTH_START", "SERVER_MAY_ISSUE_SINGLE_USE_PAPER_READ_ONLY_CONSENT")

import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {resolve} from 'node:path';
const root=resolve(import.meta.dirname,'..');
const read=p=>readFileSync(resolve(root,p),'utf8');
const ontology=JSON.parse(read('projects/world-atlas/subject-atlas.v1.json'));
const html=read('projects/world-atlas/index.html');
test('one canonical root, exactly 8 realms by 8 subjects',()=>{
  assert.equal(ontology.canonical_root,'fabric://8x8/core');
  assert.equal(ontology.truth,'SUBJECT_SCOPE_IS_NOT_OPERATIONAL_CAPABILITY');
  assert.equal(ontology.denominator.seed_topics,64);
  assert.equal(ontology.realms.length,8);
  assert.ok(ontology.realms.every(r=>r.topics.length===8));
  const ids=ontology.realms.flatMap(r=>r.topics.map(t=>t.id));
  assert.equal(new Set(ids).size,64);
});
test('no sector automatically carries execution authority or release claims',()=>{
  for(const realm of ontology.realms)for(const t of realm.topics){
    assert.equal(t.public_state,'TOPIC_DIRECTORY_ONLY');
    assert.equal(t.runtime_state,'NOT_ASSERTED');
    assert.equal(t.authority,'NONE');
    assert.equal(t.indexable_detail_page,false);
  }
  assert.equal(ontology.visibility,'PUBLIC_SAFE');
});
test('HTML is crawlable and its content matches the JSON seed',()=>{
  assert.match(html,/type="application\/ld\+json"/);
  assert.match(html,/name="description"/);
  assert.match(html,/aria-live="polite"/);
  for(const realm of ontology.realms){
    assert.ok(html.includes('id="realm-'+realm.id+'"'),realm.id);
    for(const t of realm.topics){
      assert.ok(html.includes('id="topic-'+t.slug+'"'),t.id);
      assert.ok(html.includes('<strong>'+t.name.replaceAll('&','&amp;')+'</strong>'),t.id);
    }
  }
  assert.equal((html.match(/class="topic" id=/g)||[]).length,64);
});
test('one atlas page avoids 64 low-value autogenerated URL pages',()=>{
  assert.equal((html.match(/<link rel="canonical"/g)||[]).length,0);
  assert.match(html,/research directory/i);
  assert.match(html,/topic label does not indicate an active service/i);
  assert.ok(!html.includes('schema.org/SoftwareApplication'));
});
test('public discovery is linked from an existing built surface',()=>{
  assert.ok(read('scripts/build-vercel-static.mjs').includes("'projects'"));
  assert.ok(read('projects/index.html').includes('/projects/world-atlas/'));
  assert.ok(read('README.md').includes('projects/world-atlas/index.html'));
});
